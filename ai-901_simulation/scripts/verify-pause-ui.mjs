import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createSession} from '../src/engine.js';
const {chromium}=await import(pathToFileURL(resolve(process.argv[2])).href);
const root=resolve(import.meta.dirname,'..');
const bank=JSON.parse(await readFile(resolve(root,'public/data/questions.json'),'utf8'));
const exam=JSON.parse(await readFile(resolve(root,'public/data/exam.json'),'utf8'));
const now=Date.now();
const seed=createSession(bank,exam,{count:40,minutes:1,difficulty:'all'});
seed.startedAt=now;seed.deadline=now+60000;
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const context=await browser.newContext({viewport:{width:390,height:844},offline:true});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.clock.install({time:now});
 await page.goto(process.argv[3]||pathToFileURL(resolve(root,'index.html')).href);
 await page.evaluate(s=>localStorage.setItem('ai901:v1:session',JSON.stringify(s)),seed);
 await page.reload();
 await page.getByRole('button',{name:'Retomar sessão em andamento'}).click();
 await page.clock.fastForward(15000);
 const before=await page.locator('#timer').innerText();
 await page.getByRole('button',{name:'Pausar tempo',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Retomar tempo',exact:true}).getAttribute('aria-pressed'),'true');
 await page.clock.fastForward(120000);
 assert.equal(await page.locator('#timer').innerText(),before);
 let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('ai901:v1:session')));
 assert.equal(saved.status,'active');assert.ok(Number.isFinite(saved.pausedAt));
 // Respostas continuam salvas durante a pausa.
 const q=saved.questions[saved.index];
 if(q.type==='code')for(const [id,value]of Object.entries(q.answer))await page.locator(`[data-codeblank="${id}"]`).selectOption(value);
 else if(q.type==='matching')for(const [id,value]of Object.entries(q.answer))await page.locator(`[data-match="${id}"]`).selectOption(value);
 else for(const value of q.answer)await page.locator(`input[name="answer"][value="${value}"]`).check();
 await page.reload();
 await page.getByRole('button',{name:'Retomar sessão em andamento'}).click();
 assert.equal(await page.locator('#timer').innerText(),before);
 saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('ai901:v1:session')));
 assert.deepEqual(saved.answers[q.id],q.answer);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'Retomar tempo',exact:true}).click();
 await page.clock.fastForward(5000);
 assert.notEqual(await page.locator('#timer').innerText(),before);
 await page.clock.fastForward(41000);
 assert.ok((await page.locator('.results h2').innerText()).includes('de 40 questões corretas'));
 saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('ai901:v1:session')));
 assert.equal(saved.status,'completed');assert.equal(saved.pausedAt,null);
 assert.equal(await page.locator('[data-action="toggle-timer"]').count(),0);
 assert.deepEqual(errors,[]);
 console.log('QA aprovada: pausa, retomada, persistência ao recarregar, respostas, expiração após retomada, sessão antiga e celular.');
}finally{await browser.close();}
