// QA opcional: node scripts/verify-review-ui.mjs <playwright/index.mjs>
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSession } from '../src/engine.js';
const { chromium } = await import(process.argv[2] ? pathToFileURL(resolve(process.argv[2])).href : 'playwright');
const root = resolve(import.meta.dirname, '..');
const bank = JSON.parse(await readFile(resolve(root, 'public/data/questions.json')));
const exam = JSON.parse(await readFile(resolve(root, 'public/data/exam.json')));
const active = createSession(bank, exam, {count: 40, minutes: 120, difficulty: 'hard'});
const used = new Set();
const pick = (type, extra = () => true) => {
  const q = bank.questions.find(q => q.type === type && !used.has(q.id) && extra(q));
  used.add(q.id); return structuredClone(q);
};
const questions = [pick('single'), pick('multiple'), pick('matching'), pick('code', q => q.blanks.length === 2), pick('case'), pick('single'), pick('code'), pick('single')];
const answers = {};
answers[questions[0].id] = [questions[0].options.find(o => !questions[0].answer.includes(o.id)).id];
answers[questions[1].id] = [questions[1].answer[0]];
answers[questions[2].id] = { [questions[2].left[0].id]: questions[2].answer[questions[2].left[0].id] };
const code = questions[3];
answers[code.id] = { ...code.answer, [code.blanks[1].id]: code.blanks[1].options.find(o => o.id !== code.answer[code.blanks[1].id]).id };
answers[questions[5].id] = questions[5].answer;
answers[questions[6].id] = questions[6].answer;
const completed = { ...active, id: 'review-fixture', questions, answers, flagged: [questions[0].id, questions[7].id], index: 0, status: 'completed', finishedAt: Date.now() };
const browser = await chromium.launch({headless: true, channel: 'msedge'});
try {
  const context = await browser.newContext({viewport:{width:1440,height:1100},offline:true});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(pathToFileURL(resolve(root,'index.html')).href);
  await page.evaluate(({active,completed})=>{
    localStorage.setItem('ai901:v1:session',JSON.stringify(active));
    localStorage.setItem('ai901:v1:history',JSON.stringify([completed]));
  },{active,completed});
  await page.reload();
  // Não há gabarito nem status de correção na sessão ativa.
  await page.getByRole('button',{name:'Retomar sessão em andamento'}).click();
  assert.equal(await page.locator('.option-feedback,.answer-comparison,.correct-code').count(),0);
  await page.getByRole('button',{name:'Meu histórico',exact:true}).click();
  await page.getByRole('button',{name:'Revisar sessão',exact:true}).click();
  assert.equal(await page.locator('.result-breakdown').innerText(),'✓ 2 corretas\n× 4 incorretas\n— 2 sem resposta');
  await page.getByRole('button',{name:/Revisar erros e pendentes/}).click();
  assert.equal(await page.locator('.review-card').count(),6);
  assert.equal(await page.locator('.review-card .correct-answer').count(),10);
  await page.locator('[data-reviewfilter=incorrect]').click();
  assert.equal(await page.locator('.review-card').count(),4);
  await page.locator('[data-index="0"]').click();
  assert.equal(await page.locator('.option.answer-correct').count(),1);
  assert.equal(await page.locator('.option.answer-wrong').count(),1);
  assert.equal(await page.locator('.question-dots button').count(),4);
  await page.getByRole('button',{name:'Próxima',exact:false}).click();
  assert.match(await page.locator('.question-meta').innerText(),/2 \/ 8/);
  assert.ok(await page.locator('.answer-correct .option-feedback').filter({hasText:'Não marcada'}).count());
  await page.locator('[data-index="3"]').click();
  assert.equal(await page.locator('.code-blank.incorrect').count(),1);
  assert.equal(await page.locator('.review-pair').count(),2);
  assert.equal(await page.locator('.correct-code[open]').count(),1);
  await page.getByRole('button',{name:'Voltar à lista de revisão'}).click();
  await page.locator('[data-reviewfilter=unanswered]').click();
  assert.equal(await page.locator('.review-card').count(),2);
  await page.locator('[data-reviewfilter=correct]').click();
  assert.equal(await page.locator('.review-card').count(),2);
  await page.locator('[data-reviewfilter=flagged]').click();
  assert.equal(await page.locator('.review-card').count(),2);
  await page.locator('[data-reviewfilter=all]').click();
  assert.equal(await page.locator('.review-card').count(),8);
  await page.getByLabel('Buscar questão').fill(questions[0].id);
  assert.equal(await page.locator('.review-card').count(),1);
  await page.getByLabel('Buscar questão').fill('inexistente-xyz');
  assert.equal(await page.locator('.review-card').count(),0);
  assert.equal(await page.locator('.review-empty').count(),1);
  await page.getByRole('button',{name:'Mostrar todas'}).click();
  await page.getByLabel('Tema',{exact:true}).selectOption(questions[0].topicId);
  assert.equal(await page.locator('.review-card').count(), questions.filter(q=>q.topicId===questions[0].topicId).length);
  await page.getByLabel('Tema',{exact:true}).selectOption('all');
  await page.locator('[data-reviewfilter=errors]').click();
  await page.screenshot({path:resolve(root,'preview-review-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:resolve(root,'preview-review-mobile.png'),fullPage:true});
  await page.locator('.review-card').first().screenshot({path:resolve(root,'preview-review-card-mobile.png')});
  const saved = await page.evaluate(()=>JSON.parse(localStorage.getItem('ai901:v1:session')));
  assert.deepEqual(saved,active,'Consultar histórico não pode substituir o simulado ativo');
  assert.deepEqual(errors,[]);
  console.log('Revisão aprovada: filtros, busca, tema, gabarito visual, lacunas, navegação de erros, histórico preservado e celular.');
} finally { await browser.close(); }
